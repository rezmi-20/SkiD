"use client";
import { ThemeProvider } from "next-themes";
import { LanguageProvider } from "@/context/LanguageContext";
import { LocationProvider } from "@/context/LocationContext";
import { MessagingProvider } from "@/context/MessagingContext";
import { useState, useEffect } from "react";
import { authClient } from "@/lib/auth/client";
import { NeonAuthUIProvider } from "@neondatabase/auth/react";

export default function Providers({ children }: { children: React.ReactNode }) {
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const handleError = (event: ErrorEvent) => {
      const msg = String(event.message || "");
      const file = String(event.filename || "");
      // Ignore background errors generated by browser extensions, resize observers, or hydration recovery warnings
      if (
        file.includes("chrome-extension://") ||
        file.includes("moz-extension://") ||
        msg.includes("chrome: call method") ||
        msg.includes("ResizeObserver loop") ||
        msg.includes("Minified React error #418") ||
        msg.includes("Minified React error #423") ||
        msg.includes("Minified React error #425") ||
        msg.includes("Minified React error #422") ||
        msg.includes("Hydration failed") ||
        msg.includes("hydration") ||
        msg.includes("Text content does not match")
      ) {
        return;
      }
      setError(`[CRITICAL_CRASH] ${event.message} at ${event.filename}:${event.lineno}`);
    };

    const handleRejection = (event: PromiseRejectionEvent) => {
      const msg = String(event.reason?.message || event.reason || "");
      const stack = String(event.reason?.stack || "");
      if (
        msg.includes("chrome: call method") ||
        stack.includes("chrome-extension://") ||
        stack.includes("moz-extension://") ||
        msg.includes("An unexpected response was received from the server") ||
        stack.includes("fetchServerAction")
      ) {
        event.preventDefault();
        return;
      }
    };

    window.addEventListener("error", handleError);
    window.addEventListener("unhandledrejection", handleRejection);
    return () => {
      window.removeEventListener("error", handleError);
      window.removeEventListener("unhandledrejection", handleRejection);
    };
  }, []);

  if (error) {
    return (
      <div className="fixed inset-0 z-[9999] bg-red-900 text-white p-10 font-mono text-xs overflow-auto">
        <h1 className="text-xl font-bold mb-4">APPLICATION CRASHED</h1>
        <pre className="whitespace-pre-wrap">{error}</pre>
        <button onClick={() => window.location.reload()} className="mt-6 bg-white text-black px-4 py-2 rounded">Reload Page</button>
      </div>
    );
  }

  return (
    <ThemeProvider attribute="class" defaultTheme="dark" enableSystem disableTransitionOnChange>
      <LanguageProvider>
        <LocationProvider>
          <MessagingProvider>
            <NeonAuthUIProvider authClient={authClient} emailOTP social={{ providers: ['google'] }}>
              {children}
            </NeonAuthUIProvider>
          </MessagingProvider>
        </LocationProvider>
      </LanguageProvider>
    </ThemeProvider>
  );
}
